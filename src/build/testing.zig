const std = @import("std");

pub const TestSuite = struct {
    name: []const u8,
    /// Null for the app suite, which owns sources outside standalone suites.
    sourceDir: ?[]const u8,
    tests: *std.Build.Step.Compile,
};

/// Generates a test entry point for sourceDir, excluding the supplied standalone suites.
pub fn addTestsFile(b: *std.Build, sourceDir: []const u8, suites: []const TestSuite) *std.Build.Step {
    const out = b.run(&.{
        "sh",
        "-c",
        "grep -rlE '^test( |\\{)' --include='*.zig' \"$1\" | grep -vE '/(all_tests|test_all).zig$' | sort",
        // sh -c reserves 0$ position for a name placeholder, doesn't mean anything
        "test-discovery",
        sourceDir,
    });

    const content = generateTestEntryPoint(b.allocator, sourceDir, suites, out) catch @panic("OOM");
    const generated = b.addWriteFiles().add("all_tests.zig", content);
    const update = b.addUpdateSourceFiles();
    update.addCopyFileToSource(generated, b.pathJoin(&.{ sourceDir, "all_tests.zig" }));
    return &update.step;
}

fn generateTestEntryPoint(alloc: std.mem.Allocator, sourceDir: []const u8, suites: []const TestSuite, sources: []const u8) ![]const u8 {
    var content: std.ArrayList(u8) = .empty;
    errdefer content.deinit(alloc);
    try content.ensureUnusedCapacity(alloc, 32 * 1024);
    try content.appendSlice(alloc, "// generated by build.zig, do not edit\ntest {");
    var lines = std.mem.tokenizeScalar(u8, sources, '\n');
    sources: while (lines.next()) |line| {
        for (suites) |suite| {
            if (suite.sourceDir) |dir| {
                if (std.mem.startsWith(u8, line, dir)) continue :sources;
            }
        }

        const path = std.mem.cutPrefix(u8, line, sourceDir) orelse line;
        try content.print(alloc, "\n    _ = @import(\"{s}\");", .{path});
    }
    if (content.getLast() != '{') try content.append(alloc, '\n');
    try content.appendSlice(alloc, "}\n");
    return content.toOwnedSlice(alloc);
}

test "generateTestEntryPoint handles empty and populated suites" {
    const testing = std.testing;
    const f = struct {
        fn f(sources: []const u8, expected: []const u8) !void {
            const alloc = testing.allocator;
            const content = try generateTestEntryPoint(alloc, "src/lib/cli/", &.{}, sources);
            defer alloc.free(content);
            try testing.expectEqualStrings(expected, content);
        }
    }.f;

    try f("", "// generated by build.zig, do not edit\ntest {}\n");
    try f("src/lib/cli/cli.zig\n", "// generated by build.zig, do not edit\ntest {\n    _ = @import(\"cli.zig\");\n}\n");
}
