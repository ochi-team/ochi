const std = @import("std");
const executable = @import("executable.zig");
const options = @import("options.zig");

pub const Id = enum { main, encoding, cli, sack, logging };

pub const DiscoverySpec = struct {
    sourceDir: []const u8,
    output: []const u8,
    excludeDirs: []const []const u8 = &.{},
    consumers: []const Id,
};

pub const TestSuite = struct {
    id: Id,
    tests: *std.Build.Step.Compile,
};

pub const TestSuiteSpec = struct {
    id: Id,
    root: std.Build.LazyPath,
    imports: []const std.Build.Module.Import = &.{},
    options: ?executable.RootOptions = null,
};

pub const Suites = struct {
    entries: []const TestSuite,
    byId: std.EnumArray(Id, ?*std.Build.Step.Compile) = .initFill(null),

    pub fn get(self: Suites, id: Id) *std.Build.Step.Compile {
        return self.byId.get(id).?;
    }
};

pub fn addTestSuites(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    runner: std.Build.Step.Compile.TestRunner,
    filters: []const []const u8,
    allocationFailures: bool,
    specs: []const TestSuiteSpec,
) Suites {
    const entries = b.allocator.alloc(TestSuite, specs.len) catch @panic("OOM");
    var suites: Suites = .{ .entries = entries };
    for (specs, entries) |spec, *entry| {
        const artifact = b.addTest(.{
            .root_module = b.createModule(.{
                .root_source_file = spec.root,
                .target = target,
                .optimize = optimize,
                .imports = spec.imports,
            }),
            .filters = filters,
            .test_runner = runner,
        });
        if (spec.options) |rootOptions| {
            options.addRootOptions(b, artifact, rootOptions.version, rootOptions.release, rootOptions.pprof);
        }
        options.addTestOptions(b, artifact.root_module, allocationFailures);
        suites.byId.set(spec.id, artifact);
        entry.* = .{ .id = spec.id, .tests = artifact };
    }
    return suites;
}

/// Generates test entry points, excluding the supplied standalone suites
pub fn addDiscoveries(b: *std.Build, suites: Suites, specs: []const DiscoverySpec) void {
    for (specs) |spec| {
        const step = addTestsFile(b, spec);
        for (spec.consumers) |id| suites.get(id).step.dependOn(step);
    }
}

fn addTestsFile(b: *std.Build, spec: DiscoverySpec) *std.Build.Step {
    const out = b.run(&.{
        "sh",
        "-c",
        "grep -rlE '^test( |\\{)' --include='*.zig' \"$1\" | grep -vE '/(all_tests|test_all).zig$' | sort",
        // sh -c reserves 0$ position for a name placeholder, doesn't mean anything
        "test-discovery",
        spec.sourceDir,
    });

    const content = generateTestEntryPoint(b.allocator, spec.sourceDir, spec.excludeDirs, out) catch @panic("OOM");
    const generated = b.addWriteFiles().add("all_tests.zig", content);
    const update = b.addUpdateSourceFiles();
    update.addCopyFileToSource(generated, spec.output);
    return &update.step;
}

fn generateTestEntryPoint(alloc: std.mem.Allocator, sourceDir: []const u8, excludeDirs: []const []const u8, sources: []const u8) ![]const u8 {
    var content: std.ArrayList(u8) = .empty;
    errdefer content.deinit(alloc);

    try content.ensureUnusedCapacity(alloc, 32 * 1024);
    try content.appendSlice(alloc, "// generated by build.zig, do not edit\ntest {");

    var lines = std.mem.tokenizeScalar(u8, sources, '\n');
    sources: while (lines.next()) |line| {
        for (excludeDirs) |dir| {
            if (std.mem.startsWith(u8, line, dir)) continue :sources;
        }

        const path = std.mem.cutPrefix(u8, line, sourceDir) orelse line;
        try content.print(alloc, "\n    _ = @import(\"{s}\");", .{path});
    }
    if (content.getLast() != '{') try content.append(alloc, '\n');
    try content.appendSlice(alloc, "}\n");
    return content.toOwnedSlice(alloc);
}

test "generateTestEntryPoint handles empty sources and explicit exclusions" {
    const testing = std.testing;
    const f = struct {
        fn f(sourceDir: []const u8, excludeDirs: []const []const u8, sources: []const u8, expected: []const u8) !void {
            const alloc = testing.allocator;
            const content = try generateTestEntryPoint(alloc, sourceDir, excludeDirs, sources);
            defer alloc.free(content);
            try testing.expectEqualStrings(expected, content);
        }
    }.f;

    try f("src/", &.{}, "", "// generated by build.zig, do not edit\ntest {}\n");
    try f("src/lib/cli/", &.{}, "src/lib/cli/cli.zig\n", "// generated by build.zig, do not edit\ntest {\n    _ = @import(\"cli.zig\");\n}\n");
    try f("src/", &.{ "src/lib/cli/", "src/apps/sack/" }, "src/lib/cli/cli.zig\nsrc/apps/sack/main.zig\nsrc/main.zig\nsrc/lib/cli_extra/test.zig\n", "// generated by build.zig, do not edit\ntest {\n    _ = @import(\"main.zig\");\n    _ = @import(\"lib/cli_extra/test.zig\");\n}\n");
    try f("src/", &.{"src/lib/"}, "src/lib/cli/cli.zig\n", "// generated by build.zig, do not edit\ntest {}\n");
}
